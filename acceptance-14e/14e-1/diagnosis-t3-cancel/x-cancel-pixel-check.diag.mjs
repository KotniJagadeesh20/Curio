import { setup, login, check, BASE } from './common.mjs';
import { resolveFixture } from './fixture.mjs';
const D = './';
const { browser, page } = await setup();
await login(page);
const { PAGE } = await resolveFixture(page);
await page.goto(BASE + '/create/pages/' + PAGE); await page.getByTestId('block-editor').waitFor();
await page.getByRole('button', { name: 'Add block' }).click(); await page.getByRole('menuitem', { name: 'Image', exact: true }).click();
const card = page.locator('[data-block-type=image]').last();
const color = () => card.getByAltText('Image preview').evaluate(img => { const c = document.createElement('canvas'); c.width = 1; c.height = 1; const x = c.getContext('2d'); x.drawImage(img, 0, 0); return [...x.getImageData(0, 0, 1, 1).data].slice(0, 3).join(','); });
await card.getByLabel('Image file').setInputFiles(D + 'blue.png'); await card.getByAltText('Image preview').waitFor(); await page.waitForTimeout(800);
const before = await color();
await page.route('**/api/media', (route) => route.request().method() === 'POST' ? new Promise(r => setTimeout(() => route.continue().catch(()=>{}).finally(r), 6000)) : route.continue());
await card.getByLabel('Image file').setInputFiles(D + 'red.png');
await card.getByRole('button', { name: 'Cancel upload' }).click();
await page.waitForTimeout(800);
const after = await color();
await page.waitForTimeout(6500);
const later = await color();
check('Cancel keeps the previous image (pixel check)', before === after && after === later, `${before} / ${after} / after server would have finished: ${later}`);
await browser.close();
