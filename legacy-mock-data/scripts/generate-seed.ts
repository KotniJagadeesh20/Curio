/**
 * One-time generator: turns the legacy front-end mock data into a Flyway seed migration.
 * Run with:  node scripts/run-generate-seed.mjs
 */
import fs from "node:fs";
import { tracks, topicContents, practiceProblems } from "../src/data/tracks";
import { curriculaByTrack } from "../src/data/curriculum";

const kebab = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
const iconName = (c: any) => kebab(c?.displayName ?? "book-open");
const q = (v: unknown) => `'${String(v ?? "").replace(/'/g, "''")}'`;
const json = (v: unknown) => q(JSON.stringify(v ?? []));

const out: string[] = ["-- Generated by scripts/generate-seed.ts from the legacy mock data. Do not hand-edit."];
const stats = { tracks: 0, sections: 0, lessons: 0, withContent: 0, problems: 0 };

tracks.forEach((t, i) => {
  stats.tracks++;
  out.push(
    `INSERT INTO tracks (slug, name, description, icon, color, difficulty, estimated_hours, position) VALUES (${q(t.id)}, ${q(t.name)}, ${q(t.description)}, ${q(iconName(t.icon))}, ${q(t.color)}, ${q(t.difficulty)}, ${t.estimatedHours}, ${i});`
  );
});

const usedContent = new Set<string>();
// Section-level content whose id differs from the curriculum section id.
// topicContents is keyed by bare lesson id, but some ids exist in several tracks.
// Content for these belongs to exactly one track; the others start empty.
const contentOwner: Record<string, string> = { "course-intro": "java" };
const sectionContentAlias: Record<string, string> = {
  "linux/filesystem": "files",
  "ai/agents": "ai-agents",
  "ai/production": "production-ai",
};
for (const [trackSlug, cur] of Object.entries(curriculaByTrack)) {
  cur.sections.forEach((s, si) => {
    stats.sections++;
    out.push(
      `INSERT INTO sections (track_id, slug, title, icon, position) SELECT id, ${q(s.id)}, ${q(s.title)}, ${q(iconName(s.icon))}, ${si} FROM tracks WHERE slug = ${q(trackSlug)};`
    );
    // Some topicContents entries describe a whole section; keep them as an "Overview" lesson.
    const overviewKey = sectionContentAlias[`${trackSlug}/${s.id}`] ?? s.id;
    const overview = topicContents[overviewKey];
    const lessons = overview && !s.lessons.some((l) => l.id === overviewKey)
      ? [{ id: overviewKey, title: `${s.title} Overview`, duration: undefined as string | undefined }, ...s.lessons]
      : s.lessons;
    lessons.forEach((l, li) => {
      stats.lessons++;
      const c = contentOwner[l.id] && contentOwner[l.id] !== trackSlug ? undefined : topicContents[l.id];
      if (c) { usedContent.add(l.id); stats.withContent++; }
      out.push(
        `INSERT INTO lessons (section_id, slug, title, summary, concept, real_world, common_mistakes, best_practices, interview_relevance, duration, code_language, code_example, position) ` +
        `SELECT s.id, ${q(l.id)}, ${q(l.title)}, ${q(c?.description)}, ${q(c?.content.concept)}, ${q(c?.content.realWorld)}, ${json(c?.content.commonMistakes)}, ${json(c?.content.bestPractices)}, ${q(c?.content.interviewRelevance)}, ${l.duration ? q(l.duration) : "NULL"}, ${c ? q(c.codeLanguage) : "NULL"}, ${c ? q(c.codeExample) : "NULL"}, ${li} ` +
        `FROM sections s JOIN tracks t ON t.id = s.track_id WHERE t.slug = ${q(trackSlug)} AND s.slug = ${q(s.id)};`
      );
    });
  });
}

// Detailed Two Sum content lives inline in Problem.tsx; lift it from there.
const src = fs.readFileSync("src/pages/Problem.tsx", "utf8");
const m = src.match(/const problemData = (\{[\s\S]*?\n\});/);
const two: any = m ? new Function(`return ${m[1].replace(/ as const/g, "")}`)() : null;

practiceProblems.forEach((p) => {
  stats.problems++;
  const d = p.id === "two-sum" && two ? two : null;
  out.push(
    `INSERT INTO problems (slug, track_id, title, difficulty, category, concept, description, examples, constraints, hints, solution, language, starter_code) ` +
    `SELECT ${q(p.id)}, id, ${q(p.title)}, ${q(p.difficulty)}, ${q(p.category)}, ${q(p.concept)}, ${q(d?.description ?? p.description)}, ${json(d?.examples)}, ${json(d?.constraints)}, ${json(d?.hints)}, ${q(d?.solution)}, 'java', '' FROM tracks WHERE slug = ${q(p.track)};`
  );
});

fs.writeFileSync("backend/src/main/resources/db/migration/V2__seed_content.sql", out.join("\n") + "\n");
console.log(stats);
console.log("topicContents not attached to any lesson:", Object.keys(topicContents).filter((k) => !usedContent.has(k)));
console.log("curriculum tracks without a track row:", Object.keys(curriculaByTrack).filter((k) => !tracks.some((t) => t.id === k)));
console.log("problem tracks without a track row:", [...new Set(practiceProblems.map((p) => p.track))].filter((k) => !tracks.some((t) => t.id === k)));
