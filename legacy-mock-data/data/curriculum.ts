// Helper function to get curriculum stats
export function getCurriculumStats(curriculum: TrackCurriculum) {
  let totalLessons = 0;
  let completedLessons = 0;
  
  for (const section of curriculum.sections) {
    totalLessons += section.lessons.length;
    completedLessons += section.completed;
  }
  
  return { totalLessons, completedLessons };
}
